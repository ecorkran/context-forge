// The docs map file (slice 267, D1/D4/D7): canonical path, the new-file layout, the private
// managed-block locator, and the writer. setup-ide's managed-block code is deliberately not shared.
import { mkdir, readFile, writeFile } from 'fs/promises';
import { dirname, join } from 'path';
import { isEnoent } from '../detection/pathPresent.js';
import { formatDateProject } from '../project-defaults.js';
import { DOCS_MAP_ERROR_KIND, DocsMapError, wrapFsError } from './docsMapError.js';
import { discoverMappedDocs } from './discoverDocs.js';
import { renderManagedBlock } from './renderDocsMap.js';

export const DOCS_MAP_BEGIN = '<!-- BEGIN:cf-docs-map -->';
export const DOCS_MAP_END = '<!-- END:cf-docs-map -->';
export const DOCS_MAP_INDEX = '050';
export const DOCS_MAP_SEGMENT = 'docs-map';
export const DOCS_MAP_DIR = 'project-documents/user/architecture';
export const DOCS_MAP_DOC_TYPE = 'reference';

export const DOCS_MAP_STATUS = {
  Created: 'created',
  Updated: 'updated',
  Unchanged: 'unchanged',
} as const;

export type DocsMapStatus = (typeof DOCS_MAP_STATUS)[keyof typeof DOCS_MAP_STATUS];

export interface DocsMapResult {
  path: string;
  status: DocsMapStatus;
  adrs: number;
  docs: number;
  skippedSymlinks: string[];
}

/** The canonical map path. No pattern search: a renamed project gets a new map (D1). */
export function docsMapPath(root: string, projectName: string): string {
  if (/[\\/]/.test(projectName)) {
    throw new DocsMapError(projectName, 'project name contains a path separator and cannot name the docs map file', DOCS_MAP_ERROR_KIND.Other);
  }
  return join(root, DOCS_MAP_DIR, `${DOCS_MAP_INDEX}-${DOCS_MAP_SEGMENT}.${projectName}.md`);
}

/** Plain YAML scalar when the name is plainly safe, else a double-quoted one (JSON strings are valid YAML). */
const PLAIN_YAML_NAME = /^[A-Za-z0-9](?:[A-Za-z0-9._ -]*[A-Za-z0-9._-])?$/;

function yamlScalar(value: string): string {
  return PLAIN_YAML_NAME.test(value) ? value : JSON.stringify(value);
}

/** The whole file for a project that has no map yet. All of it is cf-generated UTF-8. */
function newMapContent(projectName: string, block: string): string {
  const today = formatDateProject();
  return [
    '---',
    `docType: ${DOCS_MAP_DOC_TYPE}`,
    `project: ${yamlScalar(projectName)}`,
    `dateCreated: ${today}`,
    `dateUpdated: ${today}`,
    '---',
    '',
    `# Docs Map: ${projectName}`,
    '',
    'The block below is regenerated by `cf docs map`. Entries outside it are kept.',
    '',
    DOCS_MAP_BEGIN,
    block,
    DOCS_MAP_END,
    '',
    '## Additional Material',
    '',
  ].join('\n');
}

type BlockLocation =
  | { state: 'absent' }
  | { state: 'managed'; begin: number; end: number }
  | { state: 'broken'; problem: string };

function lineText(line: string): string {
  // Trailing whitespace (an editor's, or the line ending) does not make a marker a different line.
  return line.trimEnd();
}

function indicesOf(lines: readonly string[], marker: string): number[] {
  return lines.flatMap((line, index) => (lineText(line) === marker ? [index] : []));
}

/** Find the one BEGIN/END pair, matching whole lines. Private to the docs map (D7). */
function locateBlock(lines: readonly string[]): BlockLocation {
  const begins = indicesOf(lines, DOCS_MAP_BEGIN);
  const ends = indicesOf(lines, DOCS_MAP_END);
  if (begins.length > 1) return { state: 'broken', problem: `duplicated ${DOCS_MAP_BEGIN} marker` };
  if (ends.length > 1) return { state: 'broken', problem: `duplicated ${DOCS_MAP_END} marker` };
  if (begins.length === 0 && ends.length === 0) return { state: 'absent' };
  if (ends.length === 0) return { state: 'broken', problem: `unpaired ${DOCS_MAP_BEGIN} marker` };
  if (begins.length === 0) return { state: 'broken', problem: `unpaired ${DOCS_MAP_END} marker` };
  if (ends[0] < begins[0]) return { state: 'broken', problem: 'END marker comes before BEGIN marker' };
  return { state: 'managed', begin: begins[0], end: ends[0] };
}

/**
 * The map text with only the lines between the markers replaced. `existing` is latin1 (one char
 * per byte), so bytes outside the block survive untouched; the UTF-8 block is converted to match.
 */
function replaceBlock(existing: string, block: string, path: string): string {
  // Split after each newline so every line keeps its own ending.
  const lines = existing.split(/(?<=\n)/);
  const location = locateBlock(lines);
  if (location.state === 'absent') throw new DocsMapError(path, `no ${DOCS_MAP_BEGIN} block found`, DOCS_MAP_ERROR_KIND.Markers);
  if (location.state === 'broken') throw new DocsMapError(path, location.problem, DOCS_MAP_ERROR_KIND.Markers);
  const eol = lines[location.begin].endsWith('\r\n') ? '\r\n' : '\n';
  const inserted = Buffer.from(block, 'utf8')
    .toString('latin1')
    .split('\n')
    .map((line) => line + eol);
  return [...lines.slice(0, location.begin + 1), ...inserted, ...lines.slice(location.end)].join('');
}

/** The map's current text, or `undefined` when there is no map yet. */
async function readExistingMap(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, 'latin1');
  } catch (error) {
    // No map file yet is the normal first run: it is created below.
    if (isEnoent(error)) return undefined;
    throw wrapFsError(path, 'read the docs map', error);
  }
}

async function writeMap(path: string, content: string, encoding: BufferEncoding): Promise<void> {
  try {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, encoding);
  } catch (error) {
    throw wrapFsError(path, 'write the docs map', error);
  }
}

/** Whether the map file matches what `cf docs map` would write now. */
export const DOCS_MAP_STATE = {
  Absent: 'absent',
  Current: 'current',
  OutOfDate: 'out-of-date',
} as const;

export type DocsMapState = (typeof DOCS_MAP_STATE)[keyof typeof DOCS_MAP_STATE];

export interface DocsMapComparison {
  path: string;
  state: DocsMapState;
  adrs: number;
  docs: number;
  skippedSymlinks: string[];
  /** The text a write would produce, in `encoding`. For a current map it equals the file. */
  content: string;
  encoding: BufferEncoding;
}

/**
 * Discover, render and compare against the map on disk, without writing (slice 274, D5). Shared
 * by `writeDocsMap` and the build's freshness check. Discovery runs first, so a discovery error
 * surfaces before any map is read; broken or absent markers raise `DocsMapError`.
 */
export async function compareDocsMap(root: string, projectName: string): Promise<DocsMapComparison> {
  const discovery = await discoverMappedDocs(root);
  const block = renderManagedBlock(discovery.docs, DOCS_MAP_DIR);
  const path = docsMapPath(root, projectName);
  const existing = await readExistingMap(path);
  const counts = {
    adrs: discovery.docs.filter((doc) => doc.kind === 'adr').length,
    docs: discovery.docs.filter((doc) => doc.kind === 'doc').length,
    skippedSymlinks: discovery.skippedSymlinks,
  };
  if (existing === undefined) {
    return { path, state: DOCS_MAP_STATE.Absent, ...counts, content: newMapContent(projectName, block), encoding: 'utf8' };
  }
  const updated = replaceBlock(existing, block, path);
  const state = updated === existing ? DOCS_MAP_STATE.Current : DOCS_MAP_STATE.OutOfDate;
  return { path, state, ...counts, content: updated, encoding: 'latin1' };
}

/** Write or refresh the project's docs map. A discovery error leaves any map untouched. */
export async function writeDocsMap(root: string, projectName: string): Promise<DocsMapResult> {
  const { state, content, encoding, path, ...counts } = await compareDocsMap(root, projectName);
  if (state === DOCS_MAP_STATE.Current) return { path, status: DOCS_MAP_STATUS.Unchanged, ...counts };
  await writeMap(path, content, encoding);
  const status = state === DOCS_MAP_STATE.Absent ? DOCS_MAP_STATUS.Created : DOCS_MAP_STATUS.Updated;
  return { path, status, ...counts };
}
